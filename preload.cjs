// 预加载（CJS）：沙箱环境不支持 ESM preload，必须用 require
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  deleteAccounts: names => ipcRenderer.invoke('delete-accounts',{names}),
  deleteRevenue: ids => ipcRenderer.invoke('delete-revenue',{ids}),
  studio: (method,data) => ipcRenderer.invoke('studio',{method,data}),
  revenueCache: () => ipcRenderer.invoke('revenue-cache'),
  automationState: () => ipcRenderer.invoke('automation-state'),
  automationSyncReview: () => ipcRenderer.invoke('automation-sync-review'),
  automationCleaning: id => ipcRenderer.invoke('automation-cleaning',id),
  automationImport: (files, scheme) => ipcRenderer.invoke('automation-import', { files, scheme }),
  automationControl: (action, id, patch) => ipcRenderer.invoke('automation-control', { action, id, patch }),
  automationScheme: (action, scheme, name) => ipcRenderer.invoke('automation-scheme', { action, scheme, name }),
  automationChapters: id => ipcRenderer.invoke('automation-chapters', id),
  onAutomationState: cb => ipcRenderer.on('automation-state', (_e, state) => cb(state)),
  getSiteData: () => ipcRenderer.invoke('get-site-data'),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  saveSettings: (s) => ipcRenderer.invoke('save-settings', s),
  openPlatformLogin: phone => ipcRenderer.invoke('platform-login-open',{phone}),
  savePlatformLogin: () => ipcRenderer.invoke('platform-login-save'),
  onPlatformLoginState: cb => ipcRenderer.on('platform-login-state',(_e,d)=>cb(d)),
  getCredentials: () => ipcRenderer.invoke('get-credentials'),
  saveCredentials: (phone, password) => ipcRenderer.invoke('save-credentials', { phone, password }),
  clearCredentials: () => ipcRenderer.invoke('clear-credentials'),
  validateConfig: (cfg) => ipcRenderer.invoke('validate-config', cfg),
  pickFiles: (kind) => ipcRenderer.invoke('pick-files', { kind }),
  archiveCover: (src) => ipcRenderer.invoke('archive-cover', { src }),
  saveCover: (src, name) => ipcRenderer.invoke('save-cover', { src, name }),
  siteWorks: () => ipcRenderer.invoke('site-works'),
  prepareTask: (payload) => ipcRenderer.invoke('prepare-task', payload),
  runTasks: (tasks, mode, headless) => ipcRenderer.invoke('run-tasks', { tasks, mode, headless }),
  runControl: (action) => ipcRenderer.invoke('run-control', { action }),
  revenueSummary: (headless, opts) => ipcRenderer.invoke('revenue-summary', { headless, forceSync: !!(opts && opts.forceSync) }),
  toggleRevIgnore: (sid) => ipcRenderer.invoke('toggle-rev-ignore', { sid }),
  exportRevenueCsv: () => ipcRenderer.invoke('export-revenue-csv'),
  refreshPanel: (tasks) => ipcRenderer.invoke('refresh-panel', { tasks }),
  loadTasks: () => ipcRenderer.invoke('load-tasks'),
  saveTasks: (list) => ipcRenderer.invoke('save-tasks', list),
  loadLogs: () => ipcRenderer.invoke('load-logs'),
  listTemplates: () => ipcRenderer.invoke('list-templates'),
  saveTemplate: (name) => ipcRenderer.invoke('save-template', { name }),
  applyTemplate: (name) => ipcRenderer.invoke('apply-template', { name }),
  deleteTemplate: (name) => ipcRenderer.invoke('delete-template', { name }),
  listAccounts: () => ipcRenderer.invoke('list-accounts'),
  saveAccount: (name, phone, password) => ipcRenderer.invoke('save-account', { name, phone, password }),
  switchAccount: (name) => ipcRenderer.invoke('switch-account', { name }),
  deleteAccount: (name) => ipcRenderer.invoke('delete-account', { name }),
  onRevStatus: (cb) => ipcRenderer.on('rev-status', (_e, d) => cb(d)),
  testAi: (kind, config) => ipcRenderer.invoke('test-ai', { kind, config }),
  checkUpdate: () => ipcRenderer.invoke('check-update'),
  notifyDone: () => ipcRenderer.invoke('notify-done'),
  winControl: (action) => ipcRenderer.invoke('win-control', { action }),
  onRunProgress: (cb) => ipcRenderer.on('run-progress', (_e, d) => cb(d)),
  genCandidates: (cfg, field, count, prompt, options = {}) => ipcRenderer.invoke('gen-candidates', { cfg, field, count, prompt, options }),
  openOutput: () => ipcRenderer.invoke('open-output'),
  openPath: (p) => ipcRenderer.invoke('open-path', p),
  onLog: (cb) => ipcRenderer.on('log', (_e, d) => cb(d)),
  onRunStatus: (cb) => ipcRenderer.on('run-status', (_e, d) => cb(d)),
  onTaskStatus: (cb) => ipcRenderer.on('task-status', (_e, d) => cb(d)),
  onLoginWait: (cb) => ipcRenderer.on('login-wait', (_e, d) => cb(d)),
});
